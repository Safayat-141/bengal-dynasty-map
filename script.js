const timelineEl = document.getElementById('timeline');
const panelEl    = document.getElementById('panel');
const footCount  = document.getElementById('footCount');

let activeId = DYNASTIES[0].id;
let map;
let regionLayers = {};   // { regionKey: L.Polygon }

/* ── বাংলা সংখ্যা রূপান্তর ── */
function bnNum(n){
  const map = ['০','১','২','৩','৪','৫','৬','৭','৮','৯'];
  return String(n).replace(/\d/g, x => map[+x]);
}

/* ── মানচিত্রের প্রাথমিক সেটআপ ── */
function initMap(){
  // বাংলা অঞ্চলে কেন্দ্রীভূত
  map = L.map('map', {
    center: [23.5, 90.0],
    zoom: 6,
    zoomControl: true,
    attributionControl: true
  });

  // বিশ্বের দেশগুলোর সীমানা (হালকা ধূসর)
  fetch('https://raw.githubusercontent.com/johan/world.geo.json/master/countries.geo.json')
    .then(res => res.json())
    .then(worldData => {
      L.geoJSON(worldData, {
        style: {
          color: 'rgba(255,255,255,0.12)',
          weight: 0.6,
          fillColor: '#1a2533',
          fillOpacity: 0.9
        },
        interactive: false
      }).addTo(map);
    })
    .catch(() => {
      // ব্যাকআপ: যদি GeoJSON লোড না হয়, শুধু কালো ব্যাকগ্রাউন্ড
      console.warn('World GeoJSON লোড হয়নি — ব্যাকআপ ব্যবহার করা হচ্ছে।');
    });

  // ঐতিহাসিক অঞ্চলগুলোর polygon লেয়ার
  Object.entries(REGION_META).forEach(([key, meta]) => {
    const poly = L.polygon(meta.polygon, {
      color: 'rgba(255,255,255,0.2)',
      weight: 1.2,
      fillColor: 'rgba(255,255,255,0.05)',
      fillOpacity: 0.6,
      interactive: true
    }).addTo(map);

    // টুলটিপ
    poly.bindTooltip(`${meta.full}`, {
      sticky: true,
      direction: 'top',
      className: 'region-tooltip'
    });

    // হোভার ইফেক্ট
    poly.on('mouseover', function(){
      if (!this._isActive) {
        this.setStyle({ fillColor: 'rgba(255,255,255,0.15)', weight: 2 });
      }
    });
    poly.on('mouseout', function(){
      if (!this._isActive) {
        this.setStyle({ fillColor: 'rgba(255,255,255,0.05)', weight: 1.2 });
      }
    });

    // ক্লিক — প্রথম সংশ্লিষ্ট রাজবংশ নির্বাচন
    poly.on('click', () => {
      const first = DYNASTIES.find(d => d.regions.includes(key));
      if (first) select(first.id);
    });

    regionLayers[key] = poly;
  });

  // বাংলা অঞ্চলে জুম
  map.fitBounds([[20.0, 84.0], [27.5, 94.0]], { padding: [20, 20] });
}

/* ── টাইমলাইন চিপ তৈরি ── */
DYNASTIES.forEach(d => {
  const b = document.createElement('button');
  b.className = 'chip';
  b.dataset.id = d.id;
  b.innerHTML = `${d.short}<span>${d.period.split('–')[0].trim().replace('আনু. ','')}…</span>`;
  b.addEventListener('click', () => select(d.id));
  timelineEl.appendChild(b);
});

/* ── মূল সিলেকশন ফাংশন ── */
function select(id){
  activeId = id;
  const d = DYNASTIES.find(x => x.id === id);

  // চিপ
  document.querySelectorAll('.chip').forEach(c =>
    c.classList.toggle('active', c.dataset.id === id));

  // মানচিত্রের লেয়ার স্টাইল
  Object.entries(regionLayers).forEach(([key, poly]) => {
    const isActive = d.regions.includes(key);
    poly._isActive = isActive;
    if (isActive) {
      poly.setStyle({
        color: d.accent,
        fillColor: d.accent,
        fillOpacity: 0.45,
        weight: 2.5
      });
      poly.bringToFront();
    } else {
      poly.setStyle({
        color: 'rgba(255,255,255,0.2)',
        fillColor: 'rgba(255,255,255,0.05)',
        fillOpacity: 0.6,
        weight: 1.2
      });
    }
  });

  footCount.textContent = bnNum(d.regions.length);

  // প্যানেল
  const regionChips = Object.entries(REGION_META).map(([k, m]) =>
    `<span class="${d.regions.includes(k) ? 'on' : ''}">${m.bn}</span>`).join('');

  const rulersHTML = d.rulers.map(([n, y]) =>
    `<li><span class="rn">${n}</span><span class="ry">${y}</span></li>`).join('');

  panelEl.innerHTML = `
    <div class="p-name">${d.name}</div>
    <div class="p-period">${d.period}</div>

    <div class="stats">
      <div class="stat"><div class="k">শাসনকাল</div><div class="v">${d.span}</div></div>
      <div class="stat"><div class="k">রাজধানী</div><div class="v">${d.capital}</div></div>
      <div class="stat" style="grid-column:1/-1">
        <div class="k">শাসন অঞ্চল</div><div class="v">${d.area}</div>
      </div>
    </div>

    <div class="sect">
      <h4>🗺️ মানচিত্রে অঞ্চল</h4>
      <div class="legend">${regionChips}</div>
    </div>

    <div class="sect">
      <h4>🌾 আর্থসামাজিক অবস্থা</h4>
      <p>${d.society}</p>
    </div>

    <div class="sect">
      <h4>✅ সফলতা</h4>
      <p>${d.success}</p>
    </div>

    <div class="sect">
      <h4>⚠️ ব্যর্থতা</h4>
      <p>${d.failure}</p>
    </div>

    <div class="sect">
      <h4>📈 উত্থান</h4>
      <p>${d.rise}</p>
    </div>

    <div class="sect">
      <h4>📉 পতন</h4>
      <p>${d.fall}</p>
    </div>

    <div class="sect">
      <div class="ruler-head">
        <h4 style="flex:1">👑 শাসকগণের তালিকা</h4>
        <span class="ruler-count">${bnNum(d.rulers.length)} জন</span>
      </div>
      <ul class="rulers">${rulersHTML}</ul>
    </div>
  `;

  panelEl.scrollTop = 0;
}

/* ── আরম্ভ ── */
initMap();
select(activeId);
